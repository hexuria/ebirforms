/**
 * bun scripts/build-release.ts [outfile]  ->  one self-contained binary (default dist/ebirforms).
 *
 * GPUIX's napi-rs loader finds its native module through createRequire at run
 * time, which `bun build --compile` cannot follow, so a plain compile ships
 * without it and dies with "Cannot find native binding". This resolves the
 * host platform's .node, writes an entry that embeds it as a file and names it
 * in the loader's NAPI_RS_NATIVE_LIBRARY_PATH override, then compiles that
 * entry with the form worker. Build on each OS for that OS.
 *
 * The official forms (vendor/buwiz-validation/package, 56 MB) and print sheets
 * (vendor/buwiz-forms-html/html-frozen, 29 MB) are copied to vendor/ beside
 * the binary; the runtime looks there first (EBIRFORMS_VENDOR_DIR overrides).
 */
import { dirname, join, resolve } from 'node:path'
import { cpSync, readFileSync, rmSync, writeFileSync } from 'node:fs'

const root = resolve(import.meta.dir, '..')
const outfile = resolve(process.argv[2] ?? join(root, 'dist', process.platform === 'win32' ? 'ebirforms.exe' : 'ebirforms'))

const suffix = { darwin: `darwin-${process.arch}`, win32: `win32-${process.arch}-msvc`, linux: `linux-${process.arch}-gnu` }[process.platform as string]
if (!suffix) throw new Error(`No GPUIX native build for ${process.platform}`)
const nativeDir = dirname(Bun.resolveSync('@gpuix/native/package.json', root))
const pkgJson = Bun.resolveSync(`@gpuix/native-${suffix}/package.json`, nativeDir)
const nodeFile = join(dirname(pkgJson), JSON.parse(readFileSync(pkgJson, 'utf8')).main)

const entry = join(root, 'src', '.release-entry.ts')
writeFileSync(
  entry,
  `// Generated by scripts/build-release.ts; do not commit.\n` +
    `import nativePath from ${JSON.stringify(nodeFile)} with { type: 'file' }\n` +
    `process.env.NAPI_RS_NATIVE_LIBRARY_PATH ??= nativePath\n` +
    `await import('./app.tsx')\n`,
)
try {
  const build = Bun.spawnSync(['bun', 'build', '--compile', '--minify', entry, join(root, 'src', 'form-worker.ts'), '--outfile', outfile], { cwd: root, stdout: 'inherit', stderr: 'inherit', env: { ...process.env, NODE_ENV: 'production' } })
  if (build.exitCode !== 0) process.exit(build.exitCode ?? 1)
  const repoVendor = resolve(root, '..', '..', 'vendor')
  const outVendor = join(dirname(outfile), 'vendor')
  rmSync(outVendor, { recursive: true, force: true })
  for (const dir of [join('buwiz-validation', 'package'), join('buwiz-forms-html', 'html-frozen')]) {
    cpSync(join(repoVendor, dir), join(outVendor, dir), { recursive: true })
  }
  console.log(`built ${outfile} (native: ${suffix}) with ${outVendor}`)
} finally {
  rmSync(entry, { force: true })
}
